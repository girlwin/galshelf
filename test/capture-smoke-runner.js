'use strict';
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const {dialog} = require('electron');
const sleep = ms => new Promise(resolve => setTimeout(resolve, ms));
async function wait(predicate, label, timeout = 30000) {
  const end = Date.now() + timeout;
  while (Date.now() < end) { if (await predicate()) return; await sleep(150); }
  throw new Error('Timed out: ' + label);
}
module.exports = async ({app, window, store, capture, processes}) => {
  const results = [];
  const dir = process.env.GALSHELF_CAPTURE_FIXTURES;
  const stops = [path.join(dir, 'stop64'), path.join(dir, 'stop32'), path.join(dir, 'stop64-restart'), path.join(dir, 'stop-on-app-quit')];
  const js = code => window.webContents.executeJavaScript(code);
  const api = (method, argument) => js(`window.gal[${JSON.stringify(method)}](${argument === undefined ? '' : JSON.stringify(argument)})`);
  try {
    assert.equal(store.data.games.length, 0);
    for (const [bit, stopFile] of [['64', stops[0]], ['32', stops[1]]]) store.saveGame({title: 'Synthetic Japanese ' + bit, exePath: path.join(dir, 'CaptureFixture' + bit + '.exe'), args: [stopFile], categories: []});
    const games = store.state().games;
    const g64 = games.find(g => g.title.endsWith('64')), g32 = games.find(g => g.title.endsWith('32'));
    dialog.showOpenDialog = async () => ({canceled: false, filePaths: [process.env.GALSHELF_HOOK_ROOT]});
    await api('chooseCaptureRuntime');
    await window.reload(); await sleep(500);
    await js(`[...document.querySelectorAll('.nav-item')].find(b=>b.textContent==='日语学习').click()`);
    await wait(() => js(`!!document.querySelector('#capture-start')&&!document.querySelector('#capture-start').disabled`), 'learning controls');
    await js(`document.querySelector('#capture-game').value=${JSON.stringify(g64.id)};document.querySelector('#capture-game').dispatchEvent(new Event('change'));document.querySelector('#capture-start').click()`);
    await wait(() => capture.state.status === 'waiting', 'arm before launch');
    await js(`document.querySelector('#capture-launch').click()`);
    await wait(() => capture.state.connected && capture.state.latest && capture.state.streams.length >= 2, '64-bit live Japanese and multiple streams');
    assert.match(capture.state.latest.text, /[\u3040-\u30ff]/);
    results.push('64-bit game launches from the learning UI; automatic connection and live Japanese text');
    await wait(() => js(`document.querySelector('[aria-label="日文句子"]').value.length>0`), 'automatic sentence fill');
    const selected = await js(`(()=>{const node=document.querySelector('#capture-source').firstChild;const r=document.createRange();r.setStart(node,0);r.setEnd(node,2);const s=window.getSelection();s.removeAllRanges();s.addRange(r);const text=s.toString();document.querySelector('#capture-use-selection').click();return {text,word:document.querySelector('[aria-label="词语"]').value,follow:document.querySelector('#capture-follow').checked};})()`);
    assert.equal(selected.word, selected.text); assert.equal(selected.follow, false);
    await js(`document.querySelector('[aria-label="释义"]').value='未保存的释义'`);
    const frozen = await js(`document.querySelector('[aria-label="日文句子"]').value`);
    const other = capture.state.streams.find(s => !s.selected);
    await wait(() => js(`!![...document.querySelector('#capture-stream').options].find(o=>o.value===${JSON.stringify(other.id)})&&!document.querySelector('#capture-stream').disabled`), 'stream options visible in UI');
    await js(`document.querySelector('#capture-stream').value=${JSON.stringify(other.id)};document.querySelector('#capture-stream').dispatchEvent(new Event('change'))`);
    await wait(() => capture.state.selectedStreamId === other.id && capture.state.latest?.streamId === other.id, 'manual text stream selection');
    await sleep(1500);
    assert.equal(await js(`document.querySelector('[aria-label="日文句子"]').value`), frozen);
    assert.equal(await js(`document.querySelector('[aria-label="释义"]').value`), '未保存的释义');
    await js(`document.querySelector('#capture-use-sentence').click();[...document.querySelectorAll('button')].find(b=>b.textContent==='保存生词').click()`);
    await wait(async () => (await api('getStudyWords')).length === 1, 'save captured vocabulary');
    results.push('Real stream switching, selecting text, pinning a sentence, preserving edits and saving vocabulary');
    await js(`document.querySelector('.capture-panel').scrollIntoView({block:'start'})`);
    fs.writeFileSync(path.join(dir, 'learning-ui.png'), (await window.webContents.capturePage()).toPNG());
    await js(`document.querySelector('#capture-stop').click()`);
    await wait(() => capture.state.status === 'idle' && !capture.child, 'graceful detach');
    assert.ok((await api('getCaptureTargets')).some(t => t.gameId === g64.id));
    await sleep(1700); assert.equal(capture.child, null);
    await api('startCapture', {gameId: g64.id});
    await wait(() => capture.state.connected && capture.state.latest, 'reattach to still-running game');
    fs.writeFileSync(stops[0], 'exit');
    await wait(() => !capture.child && capture.state.status === 'waiting', 'game exit cleanup');
    await wait(async () => !(await api('getState')).runningGameIds.length, 'game process exits after its window closes');
    await api('saveGame', {...g64, args: [stops[2]]});
    await api('launchGame', g64.id);
    await wait(() => capture.state.connected && capture.state.latest, 'automatic connection after game restart');
    fs.writeFileSync(stops[2], 'exit');
    await wait(() => !capture.child && capture.state.status === 'waiting', 'restarted game cleanup');
    await wait(async () => !(await api('getState')).runningGameIds.length, 'launcher process cleanup');
    results.push('Stop leaves game running; reattach works; game exit and automatic reconnect use fresh process identities');
    await api('registerAccount', {loginName: 'capture_reader', displayId: 'Capture test', password: 'synthetic-password'});
    assert.equal(capture.state.latest, null); assert.deepEqual(capture.state.history, []); assert.equal(capture.armed, null);
    assert.deepEqual(await api('getStudyWords'), []);
    await api('logoutAccount'); assert.equal((await api('getStudyWords')).length, 1);
    results.push('Account switch stops capture, clears all sentences and isolates vocabulary');
    await api('startCapture', {gameId: g32.id}); await api('launchGame', g32.id);
    await wait(() => capture.state.connected && capture.state.latest, '32-bit game capture');
    assert.match(capture.state.latest.text, /[\u3040-\u30ff]/);
    await api('stopCapture'); assert.ok((await api('getCaptureTargets')).some(t => t.gameId === g32.id));
    fs.writeFileSync(stops[1], 'exit');
    await wait(async () => !(await api('getState')).runningGameIds.length, '32-bit fixture exit');
    await capture.stop({clear: true});
    assert.equal(require('../lib/study').read(store.dir).length, 1);
    results.push('32-bit native capture and detach; vocabulary survives reopening its local file');
    await api('saveGame', {...g64, args: [stops[3]]});
    await api('startCapture', {gameId: g64.id}); await api('launchGame', g64.id);
    await wait(() => capture.state.connected && capture.state.latest, 'app shutdown fixture');
    const remainingPid = capture.state.pid;
    app.once('will-quit', () => {
      const ok = !capture.child && !capture.armed && !capture.state.latest;
      results.push('Real app quit detaches capture before exit and leaves the game alive');
      fs.writeFileSync(path.join(store.dir, 'capture-smoke-result.json'), JSON.stringify({ok, results, remainingPid, stopFile: stops[3], screenshot: path.join(dir, 'learning-ui.png')}, null, 2));
      console.log(JSON.stringify({ok, results}));
    });
    app.quit();
  } catch (error) {
    console.error(error.stack);
    console.error(JSON.stringify({running:[...processes].map(([id, entry])=>({id,pid:entry.child.pid,exitCode:entry.child.exitCode,signalCode:entry.child.signalCode})),capture:capture.state}));
    for (const file of stops) fs.writeFileSync(file, 'exit');
    await capture.stop({clear: true});
    fs.writeFileSync(path.join(store.dir, 'capture-smoke-result.json'), JSON.stringify({ok: false, error: error.stack, results, capture: capture.state}, null, 2));
    app.exit(1);
  }
};
